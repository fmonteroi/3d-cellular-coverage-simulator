def generate_access_network_graph(routers: Dict[str, Router]):
    """
        Generates a zero-grade graph, given the layer-3 devices.
        The resulting graph is composed only for nodes, where each router is a single node, and its defined by its identifier.

        :param routers: routers that conform the access network -> key = router id, value = router object.

        :return [object (NetworkX.Graph)] graph: zero-grade graph composed by the routers. Each node its defined by router identifier.
    """

    graph = nx.Graph()

    i = 0
    for R in routers.values():  # Iterates the dict of routers

        graph.add_node(i, name_node=R.ND_id)  # Create a node, which principal attribute is the id of the router
        i += 1

    return graph


def linear_topology(graph: nx.graph):
    """
        Generates a graph for a access network linear topology.
        Linear topology: routers are only connected to their neighbours -> (R1)-----(R2)-----(R3)-----(R4)
        [REF] https://networkx.github.io/documentation/stable/_module/networkx/generators/classic.html#path_graph

        :param graph: zero-grade graph composed by the routers.

        :return Object (NetworkX.Graph)] graph: modified graph with the vertices generated by linear topology.
    """

    graph.add_edges_from(pairwise(graph.nodes))  # path_graph

    return graph


def complete_mesh_topology(graph: nx.graph):
    """
        Generates a graph for a access network complete mesh topology.
        Complete mesh topology: all the layer-3 devices are connected with each others, by a complete mesh.
        [REF] https://networkx.github.io/documentation/stable/_module/networkx/generators/classic.html#complete_graph

        :param graph: zero-grade graph composed by the routers.

        :return Object (NetworkX.Graph)] graph: modified graph with the vertices generated by complete mesh topology.
    """

    edges = itertools.combinations(graph.nodes, 2)  # complete_graph
    graph.add_edges_from(edges)

    return graph

