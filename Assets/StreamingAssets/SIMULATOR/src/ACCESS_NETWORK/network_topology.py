def configuration_test():
    """
        Predefined configuration for the test of the Access Network module.
        4 routers connected between them, by a closed lineal topology.
        Available resource in the routers: 100 Gbps.
        Link capacity: 100 Gb.

        :return [dict] routers: network devices generated in the predefined topology.
        :return [dict] network: links between the network devices generated in the predefined topology.
        :return [Object (NetworkX.Graph)]: connection graph of the access network (nodes are routers and vertices are links).
    """

    r1_id = "ROUTER_1"
    r2_id = "ROUTER_2"
    r3_id = "ROUTER_3"
    r4_id = "ROUTER_4"

    network = dict()
    graph = nx.Graph()
    routers = dict()

    # NODES
    graph.add_node(0, name_node=r1_id)
    graph.add_node(1, name_node=r2_id)
    graph.add_node(2, name_node=r3_id)
    graph.add_node(3, name_node=r4_id)

    # LINKS
    l1 = Link("AN_LINK_1", r1_id, r2_id, "layer3", 0, capacity=100000)  # 100Gb ethernet
    network[l1.LINK_id] = l1
    graph.add_edge(0, 1, name_edge=l1.LINK_id)

    l2 = Link("AN_LINK_2", r2_id, r3_id, "layer3", 0, capacity=100000)  # 100Gb ethernet
    network[l2.LINK_id] = l2
    graph.add_edge(1, 2, name_edge=l2.LINK_id)

    l3 = Link("AN_LINK_3", r3_id, r4_id, "layer3", 0, capacity=100000)  # 100Gb ethernet
    network[l3.LINK_id] = l3
    graph.add_edge(2, 3, name_edge=l3.LINK_id)

    l4 = Link("AN_LINK_4", r4_id, r1_id, "layer3", 0, capacity=100000)  # 100Gb ethernet
    network[l4.LINK_id] = l4
    graph.add_edge(3, 0, name_edge=l4.LINK_id)

    # ROUTERS
    r1 = Router(r1_id, 100000, None, None, bh_links=[l1.LINK_id, l4.LINK_id])
    routers[r1.ND_id] = r1

    r2 = Router(r2_id, 100000, None, None, bh_links=[l1.LINK_id, l3.LINK_id])
    routers[r2.ND_id] = r2

    r3 = Router(r3_id, 100000, None, None, bh_links=[l2.LINK_id, l4.LINK_id])
    routers[r3.ND_id] = r3

    r4 = Router(r4_id, 100000, None, None, bh_links=[l1.LINK_id, l3.LINK_id])
    routers[r4.ND_id] = r4

    return routers, network, graph


